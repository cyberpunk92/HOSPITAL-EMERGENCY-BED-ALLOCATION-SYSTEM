CREATE OR REPLACE TRIGGER TRG_UPDATE_WARD_CAPACITY
AFTER INSERT OR UPDATE OF Assignment_Status ON Bed_Assignments
FOR EACH ROW
DECLARE
    v_ward NUMBER;
BEGIN
    IF INSERTING AND :NEW.Assignment_Status = 'CURRENT' THEN
        BEGIN
            SELECT Ward_ID INTO v_ward FROM Ward_Bed_Allocation
            WHERE Bed_ID = :NEW.Bed_ID AND End_Time IS NULL;
            UPDATE Wards SET Current_Capacity = NVL(Current_Capacity, 0) + 1 WHERE Ward_ID = v_ward;
        EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;
    ELSIF UPDATING AND :OLD.Assignment_Status = 'CURRENT' AND :NEW.Assignment_Status <> 'CURRENT' THEN
        BEGIN
            SELECT Ward_ID INTO v_ward FROM Ward_Bed_Allocation
            WHERE Bed_ID = :NEW.Bed_ID AND End_Time IS NULL;
            UPDATE Wards SET Current_Capacity = GREATEST(NVL(Current_Capacity, 0) - 1, 0) WHERE Ward_ID = v_ward;
        EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_BED_HISTORY
AFTER UPDATE OF Current_Status ON Beds
FOR EACH ROW
WHEN (NEW.Current_Status != OLD.Current_Status)
BEGIN
    INSERT INTO Bed_Status_History (Bed_ID, Old_Status, New_Status)
    VALUES (:NEW.Bed_ID, :OLD.Current_Status, :NEW.Current_Status);
END;
/

CREATE OR REPLACE TRIGGER TRG_DOCTOR_HISTORY
AFTER UPDATE OF Assigned_Doctor ON Admissions
FOR EACH ROW
WHEN (NEW.Assigned_Doctor IS NOT NULL AND (OLD.Assigned_Doctor IS NULL OR NEW.Assigned_Doctor != OLD.Assigned_Doctor))
BEGIN
    INSERT INTO Doctor_Assignment_History (Admission_ID, Doctor_ID, Assignment_Time)
    VALUES (:NEW.Admission_ID, :NEW.Assigned_Doctor, CURRENT_TIMESTAMP);
END;
/

CREATE OR REPLACE TRIGGER TRG_TRANSFER_HISTORY
AFTER INSERT ON Patient_Transfers
FOR EACH ROW
BEGIN
    INSERT INTO Audit_Trails (Action_Type, Table_Name, Record_ID, Old_Value, New_Value)
    VALUES ('TRANSFER', 'Admissions', :NEW.Admission_ID,
            'Ward ' || :NEW.From_Ward, 'Ward ' || :NEW.To_Ward);
END;
/

CREATE OR REPLACE TRIGGER TRG_EQUIPMENT_AUDIT
AFTER UPDATE OF Status ON Equipment
