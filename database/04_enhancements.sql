    INSERT INTO Ambulance_Cases (Dispatcher_ID, Patient_Name, Pickup_Location, Complaint, Case_Status)
    VALUES (p_dispatcher_id, p_name, p_location, p_complaint, 'DISPATCHED')
    RETURNING Case_ID INTO p_case_id;
END;
/

CREATE OR REPLACE PROCEDURE PR_GENERATE_DAILY_REPORT AS
    v_total NUMBER;
    v_occ   NUMBER;
    v_avail NUMBER;
BEGIN
    SELECT COUNT(*),
           NVL(SUM(CASE WHEN Current_Status = 'OCCUPIED'  THEN 1 ELSE 0 END), 0),
           NVL(SUM(CASE WHEN Current_Status = 'AVAILABLE' THEN 1 ELSE 0 END), 0)
    INTO v_total, v_occ, v_avail
    FROM Beds;

    UPDATE Hospitals
    SET Total_Beds = v_total, Occupied_Beds = v_occ, Available_Beds = v_avail
    WHERE Hospital_ID = (SELECT MIN(Hospital_ID) FROM Hospitals);

    IF SQL%ROWCOUNT = 0 THEN
        INSERT INTO Hospitals (Hospital_Name, Total_Beds, Occupied_Beds, Available_Beds)
        VALUES ('HEBAS Central Hospital', v_total, v_occ, v_avail);
    END IF;
END;
/

