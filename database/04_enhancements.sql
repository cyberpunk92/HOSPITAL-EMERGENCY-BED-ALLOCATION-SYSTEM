CREATE OR REPLACE FUNCTION FN_GET_AVAILABLE_BEDS (p_ward_id IN NUMBER DEFAULT NULL)
RETURN NUMBER IS
    v_count NUMBER;
BEGIN
    IF p_ward_id IS NULL THEN
        SELECT COUNT(*) INTO v_count FROM Beds WHERE Current_Status = 'AVAILABLE';
    ELSE
        SELECT COUNT(*) INTO v_count
        FROM Beds b
        JOIN Ward_Bed_Allocation wba ON wba.Bed_ID = b.Bed_ID AND wba.End_Time IS NULL
        WHERE wba.Ward_ID = p_ward_id AND b.Current_Status = 'AVAILABLE';
    END IF;
    RETURN v_count;
END;
/

CREATE OR REPLACE FUNCTION FN_GET_WARD_OCCUPANCY (p_ward_id IN NUMBER)
RETURN NUMBER IS
    v_total NUMBER;
    v_occ   NUMBER;
BEGIN
    SELECT COUNT(*), NVL(SUM(CASE WHEN b.Current_Status = 'OCCUPIED' THEN 1 ELSE 0 END), 0)
    INTO v_total, v_occ
    FROM Beds b
    JOIN Ward_Bed_Allocation wba ON wba.Bed_ID = b.Bed_ID AND wba.End_Time IS NULL
    WHERE wba.Ward_ID = p_ward_id;
    IF v_total IS NULL OR v_total = 0 THEN RETURN 0; END IF;
    RETURN ROUND((v_occ / v_total) * 100, 1);
END;
/

CREATE OR REPLACE FUNCTION FN_GET_DOCTOR_WORKLOAD (p_doctor_id IN NUMBER)
RETURN NUMBER IS
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
    FROM Admissions
    WHERE Assigned_Doctor = p_doctor_id AND Admission_Status = 'ACTIVE';
    RETURN v_count;
END;
/

CREATE OR REPLACE FUNCTION FN_GET_NURSE_WORKLOAD (p_nurse_id IN NUMBER)
RETURN NUMBER IS
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
    FROM Admissions a
    JOIN Bed_Assignments ba ON ba.Admission_ID = a.Admission_ID AND ba.Assignment_Status = 'CURRENT'
    JOIN Ward_Bed_Allocation wba ON wba.Bed_ID = ba.Bed_ID AND wba.End_Time IS NULL
    JOIN Nurses n ON n.Assigned_Ward = wba.Ward_ID
    WHERE n.Nurse_ID = p_nurse_id AND a.Admission_Status = 'ACTIVE';
    RETURN v_count;
END;
/

CREATE OR REPLACE FUNCTION FN_GET_BED_STATUS (p_bed_id IN NUMBER)
RETURN VARCHAR2 IS
    v_status VARCHAR2(20);
BEGIN
    SELECT Current_Status INTO v_status FROM Beds WHERE Bed_ID = p_bed_id;
    RETURN v_status;
EXCEPTION WHEN NO_DATA_FOUND THEN
    RETURN NULL;
END;
/

-- ============== 5. PROCEDURES ==============
CREATE OR REPLACE PROCEDURE PR_CREATE_ADMISSION (
    p_patient_id   IN NUMBER,
    p_triage       IN NUMBER,
    p_complaint    IN VARCHAR2,
    p_admission_id OUT NUMBER
) AS
BEGIN
    INSERT INTO Admissions (Patient_ID, Triage_Priority, Chief_Complaint, Admission_Status)
    VALUES (p_patient_id, p_triage, p_complaint, 'ACTIVE')
    RETURNING Admission_ID INTO p_admission_id;
    BEGIN
        Auto_Assign_Doctor(p_admission_id);
    EXCEPTION WHEN OTHERS THEN NULL;  -- no complaint mapping: leave for manual triage
    END;
END;
/

CREATE OR REPLACE PROCEDURE PR_ASSIGN_DOCTOR (
    p_admission_id IN NUMBER,
    p_doctor_id    IN NUMBER
) AS
BEGIN
    -- Doctor_Assignment_History + doctor notification handled by triggers.
    UPDATE Admissions SET Assigned_Doctor = p_doctor_id WHERE Admission_ID = p_admission_id;
END;
/

CREATE OR REPLACE PROCEDURE PR_ASSIGN_BED (
    p_admission_id IN NUMBER,
    p_bed_id       IN NUMBER
) AS
BEGIN
    -- TRG_VALIDATE_BED_ASSIGNMENT + TRG_AUTO_OCCUPY_BED enforce rules / occupy.
    INSERT INTO Bed_Assignments (Admission_ID, Bed_ID, Assignment_Status)
    VALUES (p_admission_id, p_bed_id, 'CURRENT');
END;
/

CREATE OR REPLACE PROCEDURE PR_TRANSFER_PATIENT (
    p_admission_id IN NUMBER,
    p_to_ward      IN NUMBER
) AS
    v_bed       NUMBER;
    v_from_ward NUMBER := NULL;
    v_new_bed   NUMBER;
BEGIN
    BEGIN
        SELECT ba.Bed_ID INTO v_bed
        FROM Bed_Assignments ba
        WHERE ba.Admission_ID = p_admission_id AND ba.Assignment_Status = 'CURRENT';

        SELECT wba.Ward_ID INTO v_from_ward
        FROM Ward_Bed_Allocation wba
        WHERE wba.Bed_ID = v_bed AND wba.End_Time IS NULL;

        -- Release the current bed.
        UPDATE Bed_Assignments
        SET Assignment_Status = 'COMPLETED', End_Time = CURRENT_TIMESTAMP
        WHERE Admission_ID = p_admission_id AND Assignment_Status = 'CURRENT';
        UPDATE Beds SET Current_Status = 'PENDING_CLEANING' WHERE Bed_ID = v_bed;
    EXCEPTION WHEN NO_DATA_FOUND THEN
        v_bed := NULL;  -- patient had no current bed
    END;

    INSERT INTO Patient_Transfers (Admission_ID, From_Ward, To_Ward)
    VALUES (p_admission_id, v_from_ward, p_to_ward);

    -- Place the patient in an available bed in the target ward, if any.
    BEGIN
        SELECT b.Bed_ID INTO v_new_bed
        FROM Beds b
        JOIN Ward_Bed_Allocation wba ON wba.Bed_ID = b.Bed_ID AND wba.End_Time IS NULL
        WHERE wba.Ward_ID = p_to_ward AND b.Current_Status = 'AVAILABLE'
        FETCH FIRST 1 ROWS ONLY;
        INSERT INTO Bed_Assignments (Admission_ID, Bed_ID, Assignment_Status)
        VALUES (p_admission_id, v_new_bed, 'CURRENT');
    EXCEPTION WHEN NO_DATA_FOUND THEN NULL;  -- no free bed in target ward
    END;
END;
/

CREATE OR REPLACE PROCEDURE PR_DISCHARGE_PATIENT (
    p_admission_id IN NUMBER
) AS
BEGIN
    -- TRG_AUTO_DISCHARGE_WORKFLOW frees bed + dispatches sanitization.
    UPDATE Admissions
    SET Discharge_Timestamp = CURRENT_TIMESTAMP, Admission_Status = 'DISCHARGED'
    WHERE Admission_ID = p_admission_id AND Admission_Status = 'ACTIVE';
END;
/

CREATE OR REPLACE PROCEDURE PR_ASSIGN_NURSE (
    p_nurse_id     IN NUMBER,
    p_admission_id IN NUMBER
) AS
BEGIN
    -- TRG_NOTIFY_NURSE notifies the nurse.
    INSERT INTO Nurse_Assignments (Nurse_ID, Admission_ID)
    VALUES (p_nurse_id, p_admission_id);
END;
/

CREATE OR REPLACE PROCEDURE PR_COMPLETE_SANITIZATION (
    p_sanitization_id IN NUMBER
) AS
    v_bed NUMBER;
BEGIN
    UPDATE Sanitization_Logs
    SET Checking_Status = 'COMPLETED', End_Timestamp = CURRENT_TIMESTAMP
    WHERE Sanitization_ID = p_sanitization_id AND Checking_Status <> 'COMPLETED'
    RETURNING Bed_ID INTO v_bed;

    IF v_bed IS NOT NULL THEN
        UPDATE Beds SET Current_Status = 'AVAILABLE'
        WHERE Bed_ID = v_bed AND Current_Status = 'PENDING_CLEANING';
    END IF;
END;
/

CREATE OR REPLACE PROCEDURE PR_UPDATE_EQUIPMENT_STATUS (
    p_equipment_id IN NUMBER,
    p_status       IN VARCHAR2
) AS
BEGIN
    -- TRG_EQUIPMENT_AUDIT logs; TRG_MAINTENANCE_REQUEST opens a request if BROKEN.
    UPDATE Equipment SET Status = p_status WHERE Equipment_ID = p_equipment_id;
END;
/

CREATE OR REPLACE PROCEDURE PR_CREATE_AMBULANCE_CASE (
    p_dispatcher_id IN NUMBER,
    p_name          IN VARCHAR2,
    p_location      IN VARCHAR2,
    p_complaint     IN VARCHAR2,
    p_case_id       OUT NUMBER
) AS
