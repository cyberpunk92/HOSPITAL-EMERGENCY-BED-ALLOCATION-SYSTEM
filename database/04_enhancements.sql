CREATE OR REPLACE TRIGGER TRG_AUTO_TRIAGE
BEFORE INSERT ON Admissions
FOR EACH ROW
WHEN (NEW.Triage_Priority IS NULL)
BEGIN
    IF :NEW.Chief_Complaint IS NULL THEN
        :NEW.Triage_Priority := 3;
    ELSIF UPPER(:NEW.Chief_Complaint) LIKE '%CHEST%'
       OR UPPER(:NEW.Chief_Complaint) LIKE '%STROKE%'
       OR UPPER(:NEW.Chief_Complaint) LIKE '%SHOCK%'
       OR UPPER(:NEW.Chief_Complaint) LIKE '%UNRESPONSIVE%'
       OR UPPER(:NEW.Chief_Complaint) LIKE '%BREATH%' THEN
        :NEW.Triage_Priority := 5;
    ELSIF UPPER(:NEW.Chief_Complaint) LIKE '%TRAUMA%'
       OR UPPER(:NEW.Chief_Complaint) LIKE '%FRACTURE%'
       OR UPPER(:NEW.Chief_Complaint) LIKE '%BLEED%' THEN
        :NEW.Triage_Priority := 4;
    ELSE
        :NEW.Triage_Priority := 2;
    END IF;
END;
/

