/

CREATE OR REPLACE TRIGGER TRG_ADMISSION_AUDIT
AFTER INSERT OR UPDATE OF Admission_Status ON Admissions
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO Audit_Trails (Action_Type, Table_Name, Record_ID, New_Value)
        VALUES ('INSERT', 'Admissions', :NEW.Admission_ID, :NEW.Admission_Status);
    ELSE
        INSERT INTO Audit_Trails (Action_Type, Table_Name, Record_ID, Old_Value, New_Value)
        VALUES ('UPDATE', 'Admissions', :NEW.Admission_ID, :OLD.Admission_Status, :NEW.Admission_Status);
    END IF;
END;
/

