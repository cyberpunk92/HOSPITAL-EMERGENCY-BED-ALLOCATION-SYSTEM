WHEN (NEW.Status != OLD.Status)
BEGIN
    INSERT INTO Audit_Trails (Action_Type, Table_Name, Record_ID, Old_Value, New_Value)
    VALUES ('UPDATE', 'Equipment', :NEW.Equipment_ID, :OLD.Status, :NEW.Status);
