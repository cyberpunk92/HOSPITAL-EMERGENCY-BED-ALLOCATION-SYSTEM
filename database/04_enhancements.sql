-- ============== 1. PATIENT_PRIORITY ==============
CREATE TABLE Patient_Priority (
    Priority_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Admission_ID     NUMBER NOT NULL,
    Doctor_ID        NUMBER,
    Initial_Checkup  VARCHAR2(500),
    Priority_Level   NUMBER CHECK (Priority_Level BETWEEN 1 AND 5),
    Priority_Status  VARCHAR2(20) DEFAULT 'ACTIVE',
    Created_At       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pp_adm FOREIGN KEY (Admission_ID) REFERENCES Admissions(Admission_ID),
    CONSTRAINT fk_pp_doc FOREIGN KEY (Doctor_ID)    REFERENCES Doctor_Profiles(Doctor_ID)
);

-- ============== 2. INDEXES (idempotent: skips existing / already-indexed cols) ==============
BEGIN
    FOR s IN (
        SELECT 'IDX_ADM_PATIENT'        nm, 'Admissions(Patient_ID)'           col FROM dual UNION ALL
        SELECT 'IDX_ADM_DOCTOR',             'Admissions(Assigned_Doctor)'          FROM dual UNION ALL
        SELECT 'IDX_BA_ADMISSION',           'Bed_Assignments(Admission_ID)'        FROM dual UNION ALL
        SELECT 'IDX_BA_BED',                 'Bed_Assignments(Bed_ID)'              FROM dual UNION ALL
        SELECT 'IDX_PP_NATIONALID',          'Patient_Profile(National_ID)'         FROM dual UNION ALL
        SELECT 'IDX_CM_COMPLAINT',           'Complaint_Mapping(Complaint_Name)'    FROM dual UNION ALL
        SELECT 'IDX_NOTIF_USER',             'Notifications(User_ID)'               FROM dual UNION ALL
        SELECT 'IDX_PT_ADMISSION',           'Patient_Transfers(Admission_ID)'      FROM dual UNION ALL
        SELECT 'IDX_NA_NURSE',               'Nurse_Assignments(Nurse_ID)'          FROM dual UNION ALL
        SELECT 'IDX_AC_DISPATCHER',          'Ambulance_Cases(Dispatcher_ID)'       FROM dual UNION ALL
        SELECT 'IDX_PPR_ADMISSION',          'Patient_Priority(Admission_ID)'       FROM dual
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'CREATE INDEX ' || s.nm || ' ON ' || s.col;
        EXCEPTION WHEN OTHERS THEN
            -- ORA-00955 name in use, ORA-01408 column list already indexed
            IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
        END;
    END LOOP;
END;
/

