-- ============== 7. VIEWS ==============
CREATE OR REPLACE VIEW VW_ACTIVE_ADMISSIONS AS
SELECT a.Admission_ID, a.Patient_ID, p.Full_Name, a.Triage_Priority, a.Chief_Complaint,
       a.Primary_Diagnosis, a.Assigned_Doctor, du.FName || ' ' || du.LName AS Doctor_Name,
       b.Bed_Number, a.Arrival_Timestamp
FROM Admissions a
JOIN Patient_Profile p ON p.Patient_ID = a.Patient_ID
LEFT JOIN HEBAS_Users du ON du.UserID = a.Assigned_Doctor
LEFT JOIN Bed_Assignments ba ON ba.Admission_ID = a.Admission_ID AND ba.Assignment_Status = 'CURRENT'
LEFT JOIN Beds b ON b.Bed_ID = ba.Bed_ID
WHERE a.Admission_Status = 'ACTIVE';

CREATE OR REPLACE VIEW VW_DOCTOR_WORKLOAD AS
SELECT d.Doctor_ID, u.FName || ' ' || u.LName AS Doctor_Name, d.Specialization, d.Department,
       COUNT(a.Admission_ID) AS Active_Patients
FROM Doctor_Profiles d
JOIN HEBAS_Users u ON u.UserID = d.Doctor_ID
LEFT JOIN Admissions a ON a.Assigned_Doctor = d.Doctor_ID AND a.Admission_Status = 'ACTIVE'
GROUP BY d.Doctor_ID, u.FName, u.LName, d.Specialization, d.Department;

CREATE OR REPLACE VIEW VW_NURSE_WORKLOAD AS
SELECT n.Nurse_ID, u.FName || ' ' || u.LName AS Nurse_Name, n.Assigned_Ward,
       (SELECT COUNT(*) FROM Admissions a
        JOIN Bed_Assignments ba ON ba.Admission_ID = a.Admission_ID AND ba.Assignment_Status = 'CURRENT'
        JOIN Ward_Bed_Allocation wba ON wba.Bed_ID = ba.Bed_ID AND wba.End_Time IS NULL
        WHERE wba.Ward_ID = n.Assigned_Ward AND a.Admission_Status = 'ACTIVE') AS Ward_Patients,
       (SELECT COUNT(*) FROM Nurse_Tasks t WHERE t.Nurse_ID = n.Nurse_ID AND t.Task_Status = 'PENDING') AS Pending_Tasks
FROM Nurses n
JOIN HEBAS_Users u ON u.UserID = n.Nurse_ID;

CREATE OR REPLACE VIEW VW_AVAILABLE_BEDS AS
SELECT b.Bed_ID, b.Bed_Number, b.Bed_Type, b.Bed_Size, wba.Ward_ID, w.Ward_Type
FROM Beds b
JOIN Ward_Bed_Allocation wba ON wba.Bed_ID = b.Bed_ID AND wba.End_Time IS NULL
JOIN Wards w ON w.Ward_ID = wba.Ward_ID
WHERE b.Current_Status = 'AVAILABLE';

CREATE OR REPLACE VIEW VW_OCCUPIED_BEDS AS
SELECT b.Bed_ID, b.Bed_Number, wba.Ward_ID, w.Ward_Type, a.Admission_ID, p.Full_Name
FROM Beds b
JOIN Ward_Bed_Allocation wba ON wba.Bed_ID = b.Bed_ID AND wba.End_Time IS NULL
JOIN Wards w ON w.Ward_ID = wba.Ward_ID
JOIN Bed_Assignments ba ON ba.Bed_ID = b.Bed_ID AND ba.Assignment_Status = 'CURRENT'
JOIN Admissions a ON a.Admission_ID = ba.Admission_ID
JOIN Patient_Profile p ON p.Patient_ID = a.Patient_ID
WHERE b.Current_Status = 'OCCUPIED';

CREATE OR REPLACE VIEW VW_PENDING_SANITIZATION AS
SELECT s.Sanitization_ID, s.Bed_ID, b.Bed_Number, s.Maintenance_ID,
       u.FName || ' ' || u.LName AS Staff_Name, s.Checking_Status,
       s.Start_Timestamp, s.Equipment_Type
FROM Sanitization_Logs s
JOIN Beds b ON b.Bed_ID = s.Bed_ID
LEFT JOIN HEBAS_Users u ON u.UserID = s.Maintenance_ID
WHERE s.Checking_Status <> 'COMPLETED';

CREATE OR REPLACE VIEW VW_EQUIPMENT_STATUS AS
SELECT Equipment_ID, Equipment_Name, Equipment_Type, Size_Area, Status FROM Equipment;

